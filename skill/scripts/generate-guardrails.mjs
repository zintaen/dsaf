#!/usr/bin/env node
/**
 * DSAF v0.2.0 — CI & AI-Agent Design Guardrail Generator (+SG).
 * Emits zero-dependency discipline checker script, GitHub Actions workflow template,
 * and concise AI agent coding rules for downstream repos.
 */

import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { parseArgs } from "node:util";

function buildDisciplineChecker(stack) {
  const checkTailwind = stack === "tailwind" || stack === "react";
  return `#!/usr/bin/env node
/**
 * Generated by DSAF v0.1.0 (+SG). Zero-dependency Design Discipline Gate.
 * Checks for hardcoded colors outside token blocks, !important overrides${checkTailwind ? ", and Tailwind arbitrary values" : ""}.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { extname, join, relative, resolve } from "node:path";

const SKIP = new Set([".git", "node_modules", "dist", "build", ".next", "coverage", "draft", "audit-output"]);
const EXTS = new Set([".css", ".scss", ".tsx", ".jsx", ".vue", ".svelte", ".html"]);

function stripTokenBlocks(css) {
  return css
    .replace(/\\/\\*[\\s\\S]*?\\*\\//g, "")
    .replace(/(:root|\\[data-theme[^\\]]*\\]|@theme\\b)[^{]*\\{[^}]*\\}/gi, "");
}

function walk(dir, root, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(e.name)) continue;
    const full = join(dir, e.name);
    if (e.isDirectory()) walk(full, root, out);
    else if (EXTS.has(extname(e.name).toLowerCase())) {
      const rel = relative(root, full).replace(/\\\\/g, "/");
      if (!/(\\.test\\.|\\.spec\\.|\\.min\\.|public\\/assets\\/|vendor\\/)/i.test(rel)) out.push({ rel, full });
    }
  }
  return out;
}

const root = resolve(process.argv[2] || ".");
if (!existsSync(root)) {
  console.error("Path not found:", root);
  process.exit(2);
}
const maxColors = Number(process.env.DSAF_MAX_HARDCODED_COLORS ?? 0);
const maxImportant = Number(process.env.DSAF_MAX_IMPORTANT ?? 0);
let colors = 0;
let important = 0;
let twArbitrary = 0;
const findings = [];

for (const { rel, full } of walk(root, root)) {
  const raw = readFileSync(full, "utf8");
  const surface = rel.endsWith(".css") || rel.endsWith(".scss") ? stripTokenBlocks(raw) : raw;
  const nonVars = surface.replace(/--[a-zA-Z0-9_-]+\\s*:[^;}\\n]+;?/g, "");
  const cHits = (nonVars.match(/#[0-9a-fA-F]{3,8}\\b/g) || []).length;
  const iHits = (surface.match(/!important\\b/g) || []).length;
  const twHits = ${checkTailwind}
    ? (raw.match(/(?:bg|text|border|p|px|py|m|mx|my|gap|rounded)-\\[(?:#[^\\]\\s]+|\\d+(?:\\.\\d+)?px)\\]/g) || []).length
    : 0;
  colors += cHits;
  important += iHits;
  twArbitrary += twHits;
  if (cHits || iHits || twHits) findings.push({ file: rel, colors: cHits, important: iHits, twArbitrary: twHits });
}

console.log(\`DSAF_DISCIPLINE_SCAN: colors=\${colors} (max \${maxColors}), important=\${important} (max \${maxImportant}), twArbitrary=\${twArbitrary}\`);
for (const f of findings.slice(0, 15)) console.log(\`  - \${f.file}: colors=\${f.colors} important=\${f.important} twArbitrary=\${f.twArbitrary}\`);
if (colors > maxColors || important > maxImportant${checkTailwind ? " || twArbitrary > 0" : ""}) {
  console.error("DSAF_DISCIPLINE_GATE_FAILED");
  process.exit(1);
}
console.log("DSAF_DISCIPLINE_GATE_PASSED");
`;
}

function buildWorkflowYml(mode) {
  return `# Generated by DSAF v0.1.0 (+SG, Mode ${mode})
name: DSAF Design Discipline Gate

on:
  pull_request:
    branches: [main]
  push:
    branches: [main]

jobs:
  design-discipline:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Run zero-dep DSAF discipline scanner
        env:
          DSAF_MAX_HARDCODED_COLORS: "0"
          DSAF_MAX_IMPORTANT: "0"
        run: node .dsaf-guardrails/check-design-discipline.mjs src
`;
}

function buildAgentsRules(stack, mode) {
  const twNote =
    stack === "tailwind" || stack === "react"
      ? "\n- Never use arbitrary bracket utilities (`bg-[#...]`, `p-[13px]`) or raw Tailwind primitives (`bg-blue-500`) in feature code; bind to semantic design tokens."
      : "";
  return `# DSAF Design System Discipline Rules (Mode ${mode}, Stack: ${stack})

- Define design tokens solely inside \`:root\`, \`[data-theme]\`, or \`@theme\` (or W3C DTCG \`.tokens.json\`).
- Never introduce hardcoded hex/rgb colors or off-grid spacing (use 4px/8px grid tokens) in feature styles or inline styles.
- Never add \`!important\` overrides in component CSS.${twNote}
- Maintain >= 44x44px hit targets on mobile controls, WCAG 2.2 AA (>= 4.5:1 text, >= 3:1 UI borders/icons), and APCA-W3 Lc >= 60 for body copy.
- Before merging UI refactors, run \`node .dsaf-guardrails/check-design-discipline.mjs\` and DSAF scorecard diff gates (\`0\` silent regression).
`;
}

export function generateGuardrails({ outDir, stack = "tailwind", mode = "C" }) {
  const absOut = resolve(outDir);
  mkdirSync(absOut, { recursive: true });
  const files = [
    { name: "check-design-discipline.mjs", content: buildDisciplineChecker(stack) },
    { name: "dsaf-regression-gate.yml", content: buildWorkflowYml(mode) },
    { name: "AGENTS-dsaf-rules.md", content: buildAgentsRules(stack, mode) },
  ];
  for (const f of files) {
    writeFileSync(join(absOut, f.name), f.content, "utf8");
  }
  return files.map((f) => join(absOut, f.name));
}

function runSelfTest() {
  const scratch = mkdtempSync(join(tmpdir(), "dsaf-guardrails-test-"));
  try {
    const outDir = join(scratch, ".dsaf-guardrails");
    const appDir = join(scratch, "src");
    mkdirSync(appDir, { recursive: true });

    const created = generateGuardrails({ outDir, stack: "tailwind", mode: "C" });
    assert.equal(created.length, 3);
    for (const p of created) assert.ok(existsSync(p), `Missing generated guardrail ${p}`);

    // Syntax check emitted ESM scanner
    const checker = join(outDir, "check-design-discipline.mjs");
    execFileSync(process.execPath, ["--check", checker], { stdio: "pipe" });

    // Verify clean codebase passes
    writeFileSync(join(appDir, "tokens.css"), ":root { --surface: #ffffff; --ink: #111827; }\n.card { color: var(--ink); }\n");
    writeFileSync(join(appDir, "Card.tsx"), `export const Card = () => <div className="bg-surface text-ink" />;`);
    execFileSync(process.execPath, [checker, appDir], { stdio: "pipe" });

    // Verify hardcoded hex / arbitrary Tailwind drift fails
    writeFileSync(join(appDir, "Bad.tsx"), `export const Bad = () => <div className="bg-[#ff00aa]" />;`);
    let failedAsExpected = false;
    try {
      execFileSync(process.execPath, [checker, appDir], { stdio: "pipe" });
    } catch (err) {
      failedAsExpected = err.status === 1;
    }
    assert.ok(failedAsExpected, "Generated discipline checker must fail on bg-[#ff00aa]");

    const rules = readFileSync(join(outDir, "AGENTS-dsaf-rules.md"), "utf8");
    assert.match(rules, /44x44px/);

    console.log("GENERATE_GUARDRAILS_SELF_TEST_PASSED (checker syntax + pass/fail + workflow + agent rules)");
    return 0;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

function main() {
  const { values } = parseArgs({
    options: {
      out: { type: "string" },
      stack: { type: "string", default: "tailwind" },
      mode: { type: "string", default: "C" },
      "self-test": { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
  });

  if (values.help) {
    console.log("Usage: node skill/scripts/generate-guardrails.mjs --out <dir> [--stack css|tailwind|react] [--mode S|C|P] [--self-test]");
    process.exit(0);
  }
  if (values["self-test"]) process.exit(runSelfTest());
  if (!values.out) {
    console.error("Error: --out <dir> is required unless --self-test is passed.");
    process.exit(2);
  }
  const written = generateGuardrails({ outDir: values.out, stack: values.stack, mode: values.mode });
  console.log(`DSAF guardrails generated (${written.length} files):`);
  for (const w of written) console.log(`  - ${w}`);
}

const isEntry = process.argv[1] && resolve(process.argv[1]) === decodeURIComponent(new URL(import.meta.url).pathname);
if (isEntry) main();
