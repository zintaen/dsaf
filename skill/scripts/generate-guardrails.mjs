function buildAgentsRules(stack, mode) {
  const twNote =
    stack === "tailwind" || stack === "react"
      ? "\n- Never use arbitrary bracket utilities (`bg-[#...]`, `p-[13px]`) or raw Tailwind primitives (`bg-blue-500`) in feature code; bind to semantic design tokens."
      : "";
  return `# DSAF Design System Discipline Rules (v${GENERATOR_VERSION}, Mode ${mode}, Stack: ${stack})

- Define design tokens solely inside \`:root\`, \`[data-theme]\`, or \`@theme\` (or W3C DTCG \`.tokens.json\`).
- Never introduce hardcoded hex/rgb colors or off-grid spacing (use 4px/8px grid tokens) in feature CSS, \`<style>\`, or inline \`style\` props.
- Declarative SVG presentation \`fill\`/\`stroke\` brand marks and data-visualization swatch constants are reported separately (\`info: svgColors, swatchColors\`) while CSS/inline-style hex literals and Tailwind arbitrary brackets are blocked.${twNote}
- **Three-tier gates (\`Floor\` / \`Reflex\` / \`Finish\`):** Floor rules (\`transition: all\`, layout transitions, \`100vw\`, naked \`outline: none\`, unmuted \`<video autoplay>\`, hidden \`.reveal\` at rest, invalid DTCG) are **unwaivable**. Waive Reflex rules only with \`/* dsaf-ignore <rule-id> -- <concrete reason >= 12 chars> */\` and verify with \`dsaf doctor\`.
- Never add \`!important\` overrides in component CSS (keep spec-level \`[hidden]\` and \`prefers-reduced-motion\` overrides budgeted via \`DSAF_MAX_IMPORTANT\`).
- Maintain >= 44x44px hit targets on mobile controls, WCAG 2.2 AA (>= 4.5:1 text, >= 3:1 UI borders/icons), and APCA-W3 Lc >= 60 for body copy.
- Enable edit-time agent enforcement via \`npx @zintaen/dsaf hook install\` and verify before merging with \`node .dsaf-guardrails/check-design-discipline.mjs\` + \`dsaf audit\`.
`;
}

export function generateGuardrails({ outDir, stack = "tailwind", mode = "C" }) {
  const absOut = resolve(outDir);
  mkdirSync(absOut, { recursive: true });
  const files = [
    { name: "check-design-discipline.mjs", content: buildDisciplineChecker(stack) },
    { name: "dsaf-regression-gate.yml", content: buildWorkflowYml(mode) },
    { name: "AGENTS-dsaf-rules.md", content: buildAgentsRules(stack, mode) },
  ];
  for (const f of files) {
    writeFileSync(join(absOut, f.name), f.content, "utf8");
  }
  return files.map((f) => join(absOut, f.name));
}

function runGate(checker, dir, extraEnv = {}) {
  try {
    const stdout = execFileSync(process.execPath, [checker, dir], {
      encoding: "utf8",
      stdio: "pipe",
      env: { ...process.env, ...extraEnv },
    });
    return { status: 0, stdout, stderr: "" };
  } catch (err) {
    return {
      status: err.status ?? 1,
      stdout: err.stdout ? String(err.stdout) : "",
      stderr: err.stderr ? String(err.stderr) : "",
    };
  }
}

function runSelfTest() {
  const scratch = mkdtempSync(join(tmpdir(), "dsaf-guardrails-test-"));
  try {
    const outDir = join(scratch, ".dsaf-guardrails");
    const appDir = join(scratch, "src");
    mkdirSync(appDir, { recursive: true });

    const created = generateGuardrails({ outDir, stack: "tailwind", mode: "C" });
    assert.equal(created.length, 3);
    for (const p of created) assert.ok(existsSync(p), `Missing generated guardrail ${p}`);

    // Syntax check emitted ESM scanner & version banner parity
    const checker = join(outDir, "check-design-discipline.mjs");
    execFileSync(process.execPath, ["--check", checker], { stdio: "pipe" });
    const checkerSrc = readFileSync(checker, "utf8");
    const ymlSrc = readFileSync(join(outDir, "dsaf-regression-gate.yml"), "utf8");
    const rules = readFileSync(join(outDir, "AGENTS-dsaf-rules.md"), "utf8");
    assert.match(checkerSrc, new RegExp(`v${GENERATOR_VERSION.replaceAll(".", "\\.")}`));
    assert.match(ymlSrc, new RegExp(`v${GENERATOR_VERSION.replaceAll(".", "\\.")}`));
    assert.match(rules, new RegExp(`v${GENERATOR_VERSION.replaceAll(".", "\\.")}`));
    assert.doesNotMatch(checkerSrc, /v0\.1\.0/);
    assert.match(rules, /44x44px/);
    assert.match(rules, /dsaf doctor/);
    assert.match(ymlSrc, /sarif_file/);

    // 1. Clean tokens + SVG presentation hex + swatch array + 5-digit prose ID (#01585) MUST PASS
    writeFileSync(join(appDir, "tokens.css"), ":root { --surface: #ffffff; --ink: #111827; }\n.card { color: var(--ink); }\n");
    writeFileSync(
      join(appDir, "Logo.tsx"),
      `export const PALETTE = ["#e5484d", "#f5902a"];
export const Logo = () => (
  <div>
    <span>Draw #01585</span>
    <svg viewBox="0 0 24 24"><path fill="#EA4335" stroke="#4285F4" d="M0 0h24v24H0z" /></svg>
  </div>
);`
    );
    const cleanRun = runGate(checker, appDir);
    assert.equal(cleanRun.status, 0, `Clean SVG + swatch codebase must pass: ${cleanRun.stdout}\n${cleanRun.stderr}`);
    assert.match(cleanRun.stdout, /styleColors=0 \(max 0\).*twArbitrary=0 \(max 0\) \| info: svgColors=2, swatchColors=2/);
    const singleClean = runGate(checker, join(appDir, "tokens.css"));
    assert.equal(singleClean.status, 0, "Single clean CSS file target must pass");

    // 2. Optional DSAF_MAX_SVG_COLORS=0 MUST FAIL when SVG hexes exist
    const strictSvgRun = runGate(checker, appDir, { DSAF_MAX_SVG_COLORS: "0" });
    assert.equal(strictSvgRun.status, 1, "DSAF_MAX_SVG_COLORS=0 must fail when SVG hexes exist");

    // 3. Inline JSX style={{ backgroundColor: "#ff00aa" }} MUST FAIL (styleColors=1)
    const jsxFile = join(appDir, "InlineBad.tsx");
    writeFileSync(jsxFile, `export const InlineBad = () => <div style={{ backgroundColor: "#ff00aa" }} />;`);
    const jsxRun = runGate(checker, appDir);
    assert.equal(jsxRun.status, 1, "Inline JSX hex style must fail");
    assert.match(jsxRun.stdout, /styleColors=1 \(max 0\)/);
    rmSync(jsxFile);

    // 4. CSS feature rule .badge { background: #fef3c7; } MUST FAIL (styleColors=1)
    const cssFile = join(appDir, "badge.css");
    writeFileSync(cssFile, `.badge { background: #fef3c7; }`);
    const cssRun = runGate(checker, appDir);
    assert.equal(cssRun.status, 1, "CSS hex outside token block must fail");
    assert.match(cssRun.stdout, /styleColors=1 \(max 0\)/);
    const singleCssFail = runGate(checker, cssFile);
    assert.equal(singleCssFail.status, 1, "Single bad CSS file target must fail");
    assert.match(singleCssFail.stdout, /styleColors=1 \(max 0\)/);
    rmSync(cssFile);

    // 5. Tailwind arbitrary brackets MUST FAIL (twArbitrary=2, styleColors=0)
    const twFile = join(appDir, "BadTw.tsx");
    writeFileSync(twFile, `export const BadTw = () => <div className="bg-[#ff00aa] p-[13px]" />;`);
    const twRun = runGate(checker, appDir);
    assert.equal(twRun.status, 1, "Generated discipline checker must fail on bg-[#ff00aa] p-[13px]");
    assert.match(twRun.stdout, /styleColors=0 \(max 0\).*twArbitrary=2 \(max 0\)/);

    console.log(`GENERATE_GUARDRAILS_SELF_TEST_PASSED (v${GENERATOR_VERSION} style/SVG/swatch separation + single-file + Tailwind + 3-tier + SARIF)`);
    return 0;
  } finally {
    rmSync(scratch, { recursive: true, force: true });
  }
}

function main() {
  const { values } = parseArgs({
    options: {
      out: { type: "string" },
      stack: { type: "string", default: "tailwind" },
      mode: { type: "string", default: "C" },
      "self-test": { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
  });

  if (values.help) {
    console.log("Usage: node skill/scripts/generate-guardrails.mjs --out <dir> [--stack css|tailwind|react] [--mode S|C|P] [--self-test]");
    process.exit(0);
  }
  if (values["self-test"]) process.exit(runSelfTest());
  if (!values.out) {
    console.error("Error: --out <dir> is required unless --self-test is passed.");
    process.exit(2);
  }
  const written = generateGuardrails({ outDir: values.out, stack: values.stack, mode: values.mode });
  console.log(`DSAF guardrails generated (${written.length} files):`);
  for (const w of written) console.log(`  - ${w}`);
}

const isEntry = process.argv[1] && resolve(process.argv[1]) === decodeURIComponent(new URL(import.meta.url).pathname);
if (isEntry) main();
